import assert from 'node:assert/strict';
import {compileExpression,sampleSegments,validBounds,numericDerivative} from '../src/app/graph-engine.ts';
const params={a:2,b:3,c:4,t:.5};
const at=(expr,x)=>compileExpression(expr)({...params,x});
const close=(value,expected)=>assert(Math.abs(value-expected)<1e-8,`${value} ≠ ${expected}`);
close(at('-x^2',3),-9);close(at('2^3^2',0),512);close(at('x^-2',2),.25);
close(at('2x+3(x+1)',2),13);close(at('2sin(pi/2)',0),2);
close(at('a*sin(b*x+t)+c',1),2*Math.sin(3.5)+4);
close(at('ln(exp(x))',2),2);close(at('log10(100)+log2(8)',0),5);
close(at('if(x<0,sqrt(-x),sqrt(x))',-9),3);
close(at('if(x<0,-x,x^2)',3),9);close(at('root(-8,3)',0),-2);
close(at(String.raw`\frac{1}{1+\frac{x}{2}}`,2),.5);
close(at(String.raw`\frac{\sin(x)}{x}`,Math.PI/2),2/Math.PI);
close(at(String.raw`\sqrt{x^{2}+1}`,0),1);close(at('y = x² + π',2),4+Math.PI);
assert(Number.isNaN(at('ln(x)',-1)));assert(Number.isNaN(at('1/x',0)));
assert(Number.isNaN(at('if(ln(-1),1,2)',0)));
for(const expr of ['x.constructor','alert(1)','process.exit()','x=5','sin()', 'if(x,1)', 'x +','__proto__','1e999','x'.repeat(601)])assert.throws(()=>compileExpression(expr));
const bounds={xmin:-2,xmax:2,ymin:-10,ymax:10};
const segments=sampleSegments(compileExpression('1/x'),params,bounds);
assert(segments.length>=2);assert(segments.every(s=>s.every(p=>p.x<0)||s.every(p=>p.x>0)),'must not draw a line across a pole');
const sqrt=sampleSegments(compileExpression('sqrt(x)'),params,bounds);
assert(sqrt.flat().every(p=>p.x>=0));
assert(!validBounds({...bounds,xmin:3}));assert(!validBounds({...bounds,xmax:Infinity}));
close(numericDerivative(compileExpression('x^3'),{...params,x:2}),12);
console.log('PASS: real functions, parameters, operator precedence, piecewise domains, LaTeX input, parser safety, poles and numerical derivative.');
